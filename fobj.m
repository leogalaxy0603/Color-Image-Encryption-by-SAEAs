function fitness=fobj(RXY2_R,RXY2_G,RXY2_B)
% %RXY2_R(1,1)=RXY2_SP_R;RXY2_R(1,2)=RXY2_CZ_R;RXY2_R(1,3)=RXY2_DJX_R;
% RXY2_G(2,1)=RXY2_SP_G;RXY2_G(2,2)=RXY2_CZ_G;RXY2_G(2,3)=RXY2_DJX_G;
% RXY2_B(3,1)=RXY2_SP_B;RXY2_B(3,2)=RXY2_CZ_B;RXY2_B(3,3)=RXY2_DJX_B;
RXY2_SP_R=RXY2_R(1,1);RXY2_CZ_R=RXY2_R(1,2);RXY2_DJX_R=RXY2_R(1,3);
RXY2_SP_G=RXY2_G(1,1);RXY2_CZ_G=RXY2_G(1,2);RXY2_DJX_G=RXY2_G(1,3);
RXY2_SP_B=RXY2_B(1,1);RXY2_CZ_B=RXY2_B(1,2);RXY2_DJX_B=RXY2_B(1,3);
fitness_R = RXY2_SP_R + RXY2_CZ_R + RXY2_DJX_R;  % Corrected here
fitness_G=RXY2_SP_G+RXY2_CZ_G+RXY2_DJX_G;
fitness_B=RXY2_SP_B+RXY2_CZ_B+RXY2_DJX_B;
fitness=abs(fitness_R+fitness_G+fitness_B);
end